.libPaths(c('/private/tmp/harvest-Rlib',.libPaths()))
base <- '/private/tmp/gwas-harvest-stage2'
root <- file.path(base,'mss-reference-relocation-stage7')
Rcpp::sourceCpp(file.path(root,'src/preservation.cpp'))
source(file.path(root,'R/preservation.R'));source(file.path(root,'R/projection.R'))
old <- new.env(parent=.GlobalEnv)
sys.source(file.path(base,'mss-context-format3-release/R/preservation.R'),old)
sys.source(file.path(base,'mss-context-format3-release/R/projection.R'),old)
library(testthat)
# Load fixture helpers without invoking the new test blocks.
parsed <- parse(file.path(root,'tests/testthat/test-reference-relocation.R'))
for(i in 1:3)eval(parsed[[i]],.GlobalEnv)
rows <- list()
for(format in 2:3) {
 f <- .relocation_fixture(format)
 before <- old$harmonise_sumstats(f$input,old$open_reference(f$reference),frequency_type='EAF')
 after <- harmonise_sumstats(f$input,open_reference(f$reference),frequency_type='EAF')
 stopifnot(identical(before,after))
 input <- file.path(f$root,'input.tsv');write.table(f$input,input,sep='\t',quote=TRUE,row.names=FALSE)
 a <- old$harmonise_file(input,f$reference,file.path(f$root,'old-edition'),frequency_type='EAF')
 b <- harmonise_file(input,f$reference,file.path(f$root,'new-edition'),frequency_type='EAF')
 names <- c('normalized.tsv','source.tsv','source-artifact','audit.tsv','metadata.tsv','columns.tsv','reference_checksums.tsv','reference_contigs.tsv','checksums.tsv')
 for(name in names)stopifnot(identical(unname(tools::md5sum(file.path(a$path,name))),unname(tools::md5sum(file.path(b$path,name)))))
 stopifnot(identical(names(a),names(b)))
 a[c('path','created_utc')] <- NULL;b[c('path','created_utc')] <- NULL
 stopifnot(identical(a,b))
 chain <- file.path(f$root,'identity.chain');writeLines(c('chain 100 1 13 + 0 13 1 13 + 0 13 1','13'),chain)
 old_projection <- old$prepare_projection(chain,f$reference,f$reference,'SYNTHETIC','SYNTHETIC')
 new_projection <- prepare_projection(chain,f$reference,f$reference,'SYNTHETIC','SYNTHETIC')
 stopifnot(identical(old_projection$receipt,new_projection$receipt))
 old_rows <- old$harmonise_sumstats(f$input,f$reference,frequency_type='EAF',projection=old_projection)
 new_rows <- harmonise_sumstats(f$input,f$reference,frequency_type='EAF',projection=new_projection)
 stopifnot(identical(old_rows,new_rows))
 old_edition <- old$harmonise_file(input,f$reference,file.path(f$root,'old-projection'),frequency_type='EAF',projection=old_projection)
 new_edition <- harmonise_file(input,f$reference,file.path(f$root,'new-projection'),frequency_type='EAF',projection=new_projection)
 projection_files <- c(names,'projection.tsv','projection_audit.tsv')
 for(name in projection_files)stopifnot(identical(unname(tools::md5sum(file.path(old_edition$path,name))),unname(tools::md5sum(file.path(new_edition$path,name)))))
 rows[[length(rows)+1L]] <- data.frame(format=format,in_memory_complete_identical=TRUE,portable_receipt_files_byte_exact=length(names),manifest_equal_except_operational_time_and_output_path=TRUE,default_projection_receipt_identical=TRUE,projection_edition_files_byte_exact=length(projection_files))
 unlink(f$root,recursive=TRUE)
}
result <- do.call(rbind,rows)
write.table(result,file.path(base,'results/mss-reference-relocation-stage7/default-compatibility.tsv'),sep='\t',row.names=FALSE,quote=FALSE)
print(result)
