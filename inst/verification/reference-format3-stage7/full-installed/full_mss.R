a <- commandArgs(TRUE)
library(Rcpp)
library(data.table)
library(MungeSumstats)
stopifnot(normalizePath(find.package('MungeSumstats'))==normalizePath(a[[3]]))
cat('Installed DLL:',getLoadedDLLs()[['MungeSumstats']][['path']],'\n')
stopifnot(getNativeSymbolInfo('_MungeSumstats_mss_prepare_cpp',PACKAGE='MungeSumstats')$numParameters==5L)
testthat::set_max_fails(10000)
result <- testthat::test_local(a[[1]],load_package='installed',reporter='summary',stop_on_failure=FALSE)
saveRDS(result,file.path(a[[2]],'installed-full.rds'))
df <- as.data.frame(result);df$result <- NULL
write.csv(df,file.path(a[[2]],'installed-full.csv'),row.names=FALSE)
summary <- list(blocks=nrow(df),passed_assertions=sum(df$passed),failed_assertions=sum(df$failed),errors=sum(df$error),warnings=sum(df$warning),skipped_blocks=sum(df$skipped))
jsonlite::write_json(summary,file.path(a[[2]],'summary.json'),pretty=TRUE,auto_unbox=TRUE,digits=NA)
if(any(df$failed>0|df$error))quit(status=1)
